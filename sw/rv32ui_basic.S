# RV32UI 基础测试
#
# 覆盖: lui, auipc, jal, jalr, beq, bne, blt, bge, bltu, bgeu,
#       lb, lh, lw, lbu, lhu, sb, sh, sw, addi, slti, sltiu,
#       xori, ori, andi, slli, srli, srai, add, sub, sll, slt,
#       sltu, xor, srl, sra, or, and
#
# 判据: 全部通过时 s0 = 0，并写入 tohost 位置。

    .text
    .globl _start

#-----------------------------------------------------------------------------
# 测试开始
#-----------------------------------------------------------------------------
_start:
    li      s0, 0               # s0 = 错误计数

#-----------------------------------------------------------------------------
# 1. 算术立即数
#-----------------------------------------------------------------------------
    li      t0, 5
    addi    t1, t0, 3           # t1 = 8
    li      t2, 8
    bne     t1, t2, fail

    addi    t1, zero, -1        # t1 = -1
    li      t2, -1
    bne     t1, t2, fail

    li      t0, 100
    addi    t1, t0, -100        # t1 = 0
    bne     t1, zero, fail

#-----------------------------------------------------------------------------
# 2. 逻辑立即数
#-----------------------------------------------------------------------------
    li      t0, 0xF0F0
    li      t3, 0x0F0F
    xor     t1, t0, t3          # t1 = 0xFFFF
    li      t2, 0xFFFF
    bne     t1, t2, fail

    li      t0, 0xFF0
    xori    t1, t0, 0x0FF       # t1 = 0xF0F
    li      t2, 0xF0F
    bne     t1, t2, fail

    li      t0, 0xFF0
    andi    t1, t0, 0x7F0       # t1 = 0x7F0
    li      t2, 0x7F0
    bne     t1, t2, fail

    li      t0, 0x0F0
    ori     t1, t0, 0x00F       # t1 = 0x0FF
    li      t2, 0x0FF
    bne     t1, t2, fail

#-----------------------------------------------------------------------------
# 3. 移位立即数
#-----------------------------------------------------------------------------
    li      t0, 1
    slli    t1, t0, 10          # t1 = 1024
    li      t2, 1024
    bne     t1, t2, fail

    li      t0, 1024
    srli    t1, t0, 10          # t1 = 1
    li      t2, 1
    bne     t1, t2, fail

    li      t0, -1024
    srai    t1, t0, 10          # t1 = -1
    li      t2, -1
    bne     t1, t2, fail

#-----------------------------------------------------------------------------
# 4. 比较立即数
#-----------------------------------------------------------------------------
    li      t0, 5
    slti    t1, t0, 10          # t1 = 1
    li      t2, 1
    bne     t1, t2, fail

    slti    t1, t0, 5           # t1 = 0
    bne     t1, zero, fail

    sltiu   t1, t0, -1          # t1 = 1 (5 < 0xFFFFFFFF 无符号)
    li      t2, 1
    bne     t1, t2, fail

#-----------------------------------------------------------------------------
# 5. 寄存器-寄存器算术
#-----------------------------------------------------------------------------
    li      t0, 100
    li      t1, 200
    add     t2, t0, t1          # t2 = 300
    li      t3, 300
    bne     t2, t3, fail

    sub     t2, t1, t0          # t2 = 100
    li      t3, 100
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 6. 寄存器-寄存器逻辑
#-----------------------------------------------------------------------------
    li      t0, 0xF0F0F0F0
    li      t1, 0x0F0F0F0F
    xor     t2, t0, t1          # t2 = 0xFFFFFFFF
    li      t3, -1
    bne     t2, t3, fail

    and     t2, t0, t1          # t2 = 0
    bne     t2, zero, fail

    or      t2, t0, t1          # t2 = 0xFFFFFFFF
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 7. 寄存器-寄存器移位
#-----------------------------------------------------------------------------
    li      t0, 1
    li      t1, 8
    sll     t2, t0, t1          # t2 = 256
    li      t3, 256
    bne     t2, t3, fail

    li      t0, 256
    li      t1, 8
    srl     t2, t0, t1          # t2 = 1
    li      t3, 1
    bne     t2, t3, fail

    li      t0, -256
    li      t1, 8
    sra     t2, t0, t1          # t2 = -1
    li      t3, -1
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 8. 寄存器-寄存器比较
#-----------------------------------------------------------------------------
    li      t0, 5
    li      t1, 10
    slt     t2, t0, t1          # t2 = 1
    li      t3, 1
    bne     t2, t3, fail

    sltu    t2, t1, t0          # t2 = 0
    bne     t2, zero, fail

    li      t0, -1              # 0xFFFFFFFF
    li      t1, 1
    sltu    t2, t0, t1          # t2 = 0（无符号 -1 > 1）
    bne     t2, zero, fail

    slt     t2, t0, t1          # t2 = 1（有符号 -1 < 1）
    li      t3, 1
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 9. lui / auipc
#-----------------------------------------------------------------------------
    lui     t0, 0x12345         # t0 = 0x12345000
    li      t1, 0x12345000
    bne     t0, t1, fail

    lui     t0, 0xFFFFF         # t0 = 0xFFFFF000
    srli    t1, t0, 12          # t1 = 0xFFFFF
    li      t2, 0xFFFFF
    bne     t1, t2, fail

#-----------------------------------------------------------------------------
# 10. 存储 / 加载
#-----------------------------------------------------------------------------
    la      t0, scratch

    li      t1, 0x11223344
    sw      t1, 0(t0)
    lw      t2, 0(t0)
    bne     t2, t1, fail

    li      t1, 0x5566
    sh      t1, 4(t0)
    lh      t2, 4(t0)
    bne     t2, t1, fail

    li      t1, 0x77
    sb      t1, 8(t0)
    lb      t2, 8(t0)
    bne     t2, t1, fail

    # 符号扩展检查
    li      t1, 0x80
    sb      t1, 9(t0)
    lb      t2, 9(t0)           # 符号扩展 → 0xFFFFFF80
    li      t3, 0xFFFFFF80
    bne     t2, t3, fail

    lbu     t2, 9(t0)           # 零扩展 → 0x80
    li      t3, 0x80
    bne     t2, t3, fail

    li      t1, 0x8000
    sh      t1, 10(t0)
    lhu     t2, 10(t0)          # 零扩展 → 0x8000
    li      t3, 0x8000
    bne     t2, t3, fail

    lh      t2, 10(t0)          # 符号扩展 → 0xFFFF8000
    li      t3, 0xFFFF8000
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 11. 分支
#-----------------------------------------------------------------------------
    li      t0, 5
    li      t1, 5
    li      t2, 0

    beq     t0, t1, 1f
    j       fail
1:  addi    t2, t2, 1

    bne     t0, t1, fail
    addi    t2, t2, 1

    blt     t0, t1, fail                # 5 < 5 不成立
    addi    t2, t2, 1

    bge     t0, t1, 2f                  # 5 >= 5 成立
    j       fail
2:  addi    t2, t2, 1

    li      t0, 5
    li      t1, 10
    blt     t0, t1, 3f
    j       fail
3:  addi    t2, t2, 1

    bge     t0, t1, fail                # 5 >= 10 不成立
    addi    t2, t2, 1

    # 无符号比较
    li      t0, -1                      # 0xFFFFFFFF
    li      t1, 1
    bltu    t1, t0, 4f                  # 1 < 0xFFFFFFFF 成立
    j       fail
4:  addi    t2, t2, 1

    bgeu    t0, t1, 5f                  # 0xFFFFFFFF >= 1 成立
    j       fail
5:  addi    t2, t2, 1

    li      t3, 8
    bne     t2, t3, fail                # 8 个分支用例各计一次

#-----------------------------------------------------------------------------
# 12. jal / jalr
#-----------------------------------------------------------------------------
    # jal: the return address must be the instruction after the jump.
    li      t2, 0
    jal     t0, 6f
    j       fail                        # 不应到达
6:  li      t2, 1                       # 到这里说明跳转成功
    li      t3, 1
    bne     t2, t3, fail

    # jalr: jump to a computed address and return through a second jalr.
    la      t1, 7f
    jalr    t0, 0(t1)
    j       fail
7:  li      t2, 2
    li      t3, 2
    bne     t2, t3, fail

#-----------------------------------------------------------------------------
# 全部通过
#-----------------------------------------------------------------------------
pass:
    li      t0, 0x1000
    li      t1, 1
    sw      t1, 0(t0)           # 写 tohost = 1 (通过)
    j       done

fail:
    addi    s0, s0, 1
    li      t0, 0x1000
    li      t1, -1
    sw      t1, 0(t0)           # 写 tohost = -1 (失败)

done:
    j       done

#-----------------------------------------------------------------------------
    .data
    .align 4
scratch:
    .word 0
    .word 0
    .word 0
    .word 0
